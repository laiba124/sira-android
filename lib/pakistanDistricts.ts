export function normalizeDistrictText(value: string) {
  return String(value ?? "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function districtKey(province: string, name: string) {
  return `${normalizeDistrictText(province)}|${normalizeDistrictText(name)}`;
}

